#!/usr/bin/env python3
"""Validate the public project catalog and export an idempotent PostgreSQL snapshot."""
from __future__ import annotations
import re
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "public-projects.json"
OUTPUT = ROOT / "data" / "public-projects.sql"
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
FIELDS = ("slug", "name", "category", "category_label", "description", "repository_url", "website_url", "status", "featured", "marketing_priority")

def sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"

def validate_url(value: object, github: bool = False) -> bool:
    if not isinstance(value, str):
        return False
    parsed = urlparse(value)
    if parsed.scheme != "https" or not parsed.hostname:
        return False
    return parsed.hostname.lower() == "github.com" if github else True


def delete_stale_rows_sql(slugs: set[str]) -> str:
    if not slugs:
        raise ValueError("Cannot prune the database with an empty public catalog")
    current_slugs = ", ".join(sql_text(slug) for slug in sorted(slugs))
    return f"DELETE FROM public_projects WHERE slug NOT IN ({current_slugs});"

def main() -> None:
    projects = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(projects, list) or not projects:
        raise SystemExit("Catalog must be a non-empty JSON array")
    seen: set[str] = set()
    rows: list[str] = []
    for index, project in enumerate(projects, start=1):
        if not isinstance(project, dict):
            raise SystemExit(f"Entry {index} must be an object")
        missing = [field for field in FIELDS if field not in project]
        if missing:
            raise SystemExit(f"Entry {index} is missing: {', '.join(missing)}")
        slug = project["slug"]
        if not isinstance(slug, str) or not SLUG_RE.fullmatch(slug):
            raise SystemExit(f"Entry {index} has an invalid slug")
        if slug in seen:
            raise SystemExit(f"Duplicate project slug: {slug}")
        seen.add(slug)
        if not validate_url(project["repository_url"], github=True):
            raise SystemExit(f"{slug}: repository_url must be an HTTPS github.com URL")
        website = project["website_url"]
        if website is not None and not validate_url(website):
            raise SystemExit(f"{slug}: website_url must be null or a valid HTTPS URL")
        if not isinstance(project["featured"], bool):
            raise SystemExit(f"{slug}: featured must be boolean")
        priority = project["marketing_priority"]
        if not isinstance(priority, int) or not 0 <= priority <= 100:
            raise SystemExit(f"{slug}: marketing_priority must be an integer from 0 to 100")
        values = [
            sql_text(project["slug"]), sql_text(project["name"]),
            sql_text(project["category"]), sql_text(project["category_label"]),
            sql_text(project["description"]), sql_text(project["repository_url"]),
            "NULL" if website is None else sql_text(website),
            sql_text(project["status"]),
            "TRUE" if project["featured"] else "FALSE", str(priority),
        ]
        rows.append("  (" + ", ".join(values) + ")")
    columns = ", ".join(FIELDS)
    updates = ",\n".join(f"  {field} = EXCLUDED.{field}" for field in FIELDS if field != "slug")
    sql = f"""-- Generated by scripts/analyze_catalog.py; do not edit by hand.
-- Source: data/public-projects.json
-- Public catalog only. No private repository metadata is exported.
BEGIN;
CREATE TABLE IF NOT EXISTS public_projects (
  slug TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  category_label TEXT NOT NULL,
  description TEXT NOT NULL,
  repository_url TEXT NOT NULL,
  website_url TEXT NULL,
  status TEXT NOT NULL,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  marketing_priority SMALLINT NOT NULL DEFAULT 0 CHECK (marketing_priority BETWEEN 0 AND 100),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO public_projects ({columns})
VALUES
{',\n'.join(rows)}
ON CONFLICT (slug) DO UPDATE SET
{updates},
  updated_at = NOW();
{delete_stale_rows_sql(seen)}
COMMIT;
"""
    OUTPUT.write_text(sql, encoding="utf-8")
    print(f"Validated {len(projects)} public projects; wrote {OUTPUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
